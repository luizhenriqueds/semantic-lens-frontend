// FNV-1a. Not security-sensitive - it backs a cache key and a daily shuffle seed, both
// of which only need to be stable across runs.
export function fnv1a(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
